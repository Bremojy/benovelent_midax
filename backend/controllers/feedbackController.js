const crypto = require("crypto");
const FeedbackCollection = require("../models/FeedbackCollection");
const Member = require("../models/Member");
const News = require("../models/News");

const ALLOWED_TYPES = new Set(["short_text", "long_text", "email", "number", "rating", "single_choice", "multiple_choice"]);

function normalizeQuestions(questions = []) {
  return (Array.isArray(questions) ? questions : []).map((q) => ({
    id: q.id || crypto.randomUUID(),
    type: ALLOWED_TYPES.has(q.type) ? q.type : "short_text",
    label: String(q.label || "").trim().slice(0, 500),
    required: Boolean(q.required),
    options: Array.isArray(q.options) ? q.options.map((v) => String(v).trim().slice(0, 200)).filter(Boolean).slice(0, 20) : [],
  })).filter((q) => q.label).slice(0, 50);
}

function visible(collection) {
  return {
    _id: collection._id,
    title: collection.title,
    description: collection.description,
    kind: collection.kind,
    googleFormUrl: collection.googleFormUrl,
    questions: collection.questions,
    anonymous: collection.anonymous,
    preventDuplicate: collection.preventDuplicate,
    status: collection.status,
    startDate: collection.startDate,
    endDate: collection.endDate,
    promptOnLogin: Boolean(collection.promptOnLogin),
    requireOnLogin: Boolean(collection.requireOnLogin),
    promptFrequencyDays: Number(collection.promptFrequencyDays || 7),
    autoGenerated: Boolean(collection.autoGenerated),
    publishedToNews: Boolean(collection.publishedToNews),
    publishedNewsId: collection.publishedNewsId || null,
    publishedAt: collection.publishedAt || null,
    createdAt: collection.createdAt,
    responseCount: collection.responses?.length || 0,
  };
}

function validatePromptSettings({ promptOnLogin, requireOnLogin, kind }) {
  if (requireOnLogin && !promptOnLogin) {
    throw new Error("A required login feedback request must also be enabled for login prompts.");
  }
  if (requireOnLogin && kind !== "native") {
    throw new Error("Only native feedback can be required before portal access.");
  }
}

exports.list = async (req, res) => {
  const filter = req.user.role === "member" ? { status: "active" } : {};
  const docs = await FeedbackCollection.find(filter).sort({ createdAt: -1 });
  res.json({ success: true, collections: docs.map(visible) });
};

exports.create = async (req, res) => {
  try {
    const { title, description, kind, googleFormUrl, questions, anonymous, preventDuplicate, status, startDate, endDate, promptOnLogin, requireOnLogin, promptFrequencyDays, autoGenerated } = req.body || {};
    if (!String(title || "").trim() || !["native", "google_form"].includes(kind)) {
      return res.status(400).json({ success: false, message: "Title and a valid feedback type are required." });
    }
    if (kind === "google_form" && !/^https:\/\//i.test(String(googleFormUrl || ""))) {
      return res.status(400).json({ success: false, message: "A secure Google Forms HTTPS URL is required." });
    }
    if (kind === "native" && !Array.isArray(questions)) {
      return res.status(400).json({ success: false, message: "Native feedback questions are required." });
    }
    const normalizedQuestions = kind === "native" ? normalizeQuestions(questions) : [];
    if (Boolean(requireOnLogin) && (!normalizedQuestions.length || !normalizedQuestions.some((question) => question.required))) {
      return res.status(400).json({ success: false, message: "A required login feedback request must contain at least one required question." });
    }
    validatePromptSettings({ promptOnLogin: Boolean(promptOnLogin), requireOnLogin: Boolean(requireOnLogin), kind });
    const doc = await FeedbackCollection.create({
      title: String(title).trim().slice(0, 160), description: String(description || "").trim().slice(0, 2000), kind,
      googleFormUrl: kind === "google_form" ? String(googleFormUrl).trim() : "",
      questions: kind === "native" ? normalizedQuestions : [], anonymous: Boolean(anonymous),
      preventDuplicate: preventDuplicate !== false, status: ["draft", "active", "closed"].includes(status) ? status : "active",
      startDate: startDate || null, endDate: endDate || null,
      promptOnLogin: Boolean(promptOnLogin), requireOnLogin: Boolean(requireOnLogin),
      promptFrequencyDays: Math.max(0, Math.min(3650, Number(promptFrequencyDays ?? 7) || 0)),
      autoGenerated: Boolean(autoGenerated),
      createdBy: req.user._id, createdByRole: req.user.role,
    });
    res.status(201).json({ success: true, collection: visible(doc) });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
};

exports.update = async (req, res) => {
  try {
    const doc = await FeedbackCollection.findById(req.params.id);
    if (!doc) return res.status(404).json({ success: false, message: "Feedback collection not found." });
    const allowed = ["title","description","googleFormUrl","questions","anonymous","preventDuplicate","status","startDate","endDate","promptOnLogin","requireOnLogin","promptFrequencyDays","autoGenerated"];
    for (const key of allowed) {
      if (req.body[key] === undefined) continue;
      doc[key] = key === "questions" ? normalizeQuestions(req.body[key]) : req.body[key];
    }
    if (Boolean(doc.requireOnLogin) && (!doc.questions?.length || !doc.questions.some((question) => question.required))) {
      throw new Error("A required login feedback request must contain at least one required question.");
    }
    validatePromptSettings({ promptOnLogin: Boolean(doc.promptOnLogin), requireOnLogin: Boolean(doc.requireOnLogin), kind: doc.kind });
    if (doc.googleFormUrl && doc.kind === "google_form" && !/^https:\/\//i.test(doc.googleFormUrl)) {
      return res.status(400).json({ success: false, message: "Google Forms URL must use HTTPS." });
    }
    await doc.save();
    res.json({ success: true, collection: visible(doc) });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
};

