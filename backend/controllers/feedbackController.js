function csvEscape(value) {
  const text = value == null ? "" : String(value);
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function buildFeedbackCsv(doc) {
  const columns = ["submittedAt", "respondentRole", "memberNumber", "memberName", "memberEmail", ...doc.questions.map((q) => `q:${q.id}`)];
  const rows = [columns.map(csvEscape).join(",")];
  for (const r of doc.responses || []) {
    const member = r.member && typeof r.member === "object" ? r.member : null;
    const values = [
      r.submittedAt ? new Date(r.submittedAt).toISOString() : "",
      r.respondentRole || "member",
      r.anonymous ? "" : (member?.memberNumber || ""),
      r.anonymous ? "" : (member?.fullName || ""),
      r.anonymous ? "" : (member?.email || ""),
      ...doc.questions.map((q) => {
        const value = r.answers?.[q.id];
        return Array.isArray(value) ? value.join(" | ") : (value ?? "");
      }),
    ];
    rows.push(values.map(csvEscape).join(","));
  }
  return rows.join("\n");
}

function parseCsvLine(line) {
  const result = [];
  let current = "";
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (ch === '"' && quoted && line[i + 1] === '"') { current += '"'; i += 1; continue; }
    if (ch === '"') { quoted = !quoted; continue; }
    if (ch === ',' && !quoted) { result.push(current); current = ""; continue; }
    current += ch;
  }
  result.push(current);
  return result;
}

function parseCsv(text) {
  const lines = String(text || "").replace(/^\uFEFF/, "").split(/\r?\n/).filter((line) => line.trim() !== "");
  if (!lines.length) return [];
  const headers = parseCsvLine(lines[0]);
  return lines.slice(1).map((line) => {
    const values = parseCsvLine(line);
    return Object.fromEntries(headers.map((header, i) => [header, values[i] ?? ""]));
  });
}

async function normalizeImportedResponses(doc, rows) {
  const memberCache = new Map();
  const responses = [];
  for (const row of rows.slice(0, 10000)) {
    const memberNumber = String(row.memberNumber || "").trim();
    const email = String(row.memberEmail || row.email || "").trim().toLowerCase();
    let member = null;
    if (memberNumber || email) {
      const cacheKey = `${memberNumber}|${email}`;
      if (memberCache.has(cacheKey)) member = memberCache.get(cacheKey);
      else {
        member = memberNumber
          ? await Member.findOne({ memberNumber }).select("_id fullName email memberNumber")
          : await Member.findOne({ email }).select("_id fullName email memberNumber");
        memberCache.set(cacheKey, member);
      }
    }
    const answers = {};
    for (const q of doc.questions) {
      const raw = row[`q:${q.id}`] ?? row[q.id];
      if (raw === undefined || raw === "") continue;
      answers[q.id] = q.type === "multiple_choice" ? String(raw).split("|").map((v) => v.trim()).filter(Boolean).slice(0, 20) : String(raw).slice(0, 4000);
    }
    if (!Object.keys(answers).length) continue;
    responses.push({
      member: member?._id || null,
      respondentRole: ["member", "admin", "superadmin"].includes(String(row.respondentRole)) ? String(row.respondentRole) : "member",
      anonymous: !member && !memberNumber && !email,
      answers,
      submittedAt: row.submittedAt ? new Date(row.submittedAt) : new Date(),
    });
  }
  return responses;
}

exports.exportResponses = async (req, res) => {
  const doc = await FeedbackCollection.findById(req.params.id).populate("responses.member", "fullName email memberNumber");
  if (!doc) return res.status(404).json({ success: false, message: "Feedback collection not found." });
  const format = String(req.query.format || "csv").toLowerCase();
  const filename = `feedback-${String(doc.title).replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").toLowerCase() || "responses"}`;
  if (format === "json") {
    res.setHeader("Content-Disposition", `attachment; filename="${filename}.json"`);
    return res.json({ title: doc.title, exportedAt: new Date().toISOString(), questions: doc.questions, responses: doc.responses });
  }
  res.setHeader("Content-Type", "text/csv; charset=utf-8");
  res.setHeader("Content-Disposition", `attachment; filename="${filename}.csv"`);
  return res.send(buildFeedbackCsv(doc));
};

exports.importResponses = async (req, res) => {
  try {
    const doc = await FeedbackCollection.findById(req.params.id);
    if (!doc) return res.status(404).json({ success: false, message: "Feedback collection not found." });
    if (!req.file) return res.status(400).json({ success: false, message: "Upload a CSV or JSON response file." });
    const raw = req.file.buffer.toString("utf8");
    let payload;
    if (/\.json$/i.test(req.file.originalname) || String(req.file.mimetype).includes("json")) payload = JSON.parse(raw);
    else payload = parseCsv(raw);
    const rows = Array.isArray(payload) ? payload : Array.isArray(payload?.responses) ? payload.responses : [];
    if (!rows.length) return res.status(400).json({ success: false, message: "No response rows were found in the uploaded file." });
    const imported = await normalizeImportedResponses(doc, rows);
    if (!imported.length) return res.status(400).json({ success: false, message: "No usable answers were found for this feedback collection." });
    const mode = String(req.body?.mode || "append").toLowerCase();
    if (mode === "replace") doc.responses = imported;
    else doc.responses.push(...imported);
    await doc.save();
    return res.json({ success: true, imported: imported.length, responseCount: doc.responses.length, collection: visible(doc) });
  } catch (error) {
    return res.status(400).json({ success: false, message: error.message || "Could not import responses." });
  }
};

exports.publishToNews = async (req, res) => {
  const doc = await FeedbackCollection.findById(req.params.id).populate("responses.member", "fullName email memberNumber");
  if (!doc) return res.status(404).json({ success: false, message: "Feedback collection not found." });
  const responseCount = doc.responses?.length || 0;
  const title = `Feedback Report: ${doc.title}`;
  const summary = `${responseCount} response${responseCount === 1 ? "" : "s"} collected.`;
  const questionSummary = doc.questions.map((q) => {
    const values = (doc.responses || []).map((r) => r.answers?.[q.id]).filter((v) => v !== undefined && v !== "");
    if (!values.length) return `${q.label}\nNo responses.`;
    const printable = values.slice(0, 50).map((v) => Array.isArray(v) ? v.join(", ") : String(v)).join("\n• ");
    return `${q.label}\n• ${printable}`;
  }).join("\n\n");
  const content = `${summary}\n\nThis report was published by an authorised ${req.user.role === "superadmin" ? "SuperAdmin" : "Admin"} account.\n\nResponse summary\n\n${questionSummary || "No response data."}\n\nMembers can sign in to download the full response file or print this report.`;
  if (doc.publishedNewsId) {
    const existing = await News.findById(doc.publishedNewsId);
    if (existing) {
      existing.title = title;
      existing.summary = summary;
      existing.content = content;
      existing.published = true;
      existing.status = "published";
      existing.publishDate = new Date();
      existing.featured = false;
      existing.pinned = false;
      existing.feedbackReportId = doc._id;
      await existing.save();
      doc.publishedToNews = true; doc.publishedAt = new Date(); await doc.save();
      return res.json({ success: true, news: existing, collection: visible(doc), updated: true });
    }
  }
  const slug = `${title}-${Date.now()}`.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const news = await News.create({
    title, slug, summary, content, category: "General", published: true, status: "published", publishDate: new Date(), author: req.user._id, feedbackReportId: doc._id,
  });
  doc.publishedToNews = true; doc.publishedNewsId = news._id; doc.publishedAt = new Date(); await doc.save();
  return res.json({ success: true, news, collection: visible(doc), updated: false });
};

exports.memberDownload = async (req, res) => {
  const doc = await FeedbackCollection.findOne({ _id: req.params.id, publishedToNews: true }).populate("responses.member", "fullName email memberNumber");
  if (!doc) return res.status(404).json({ success: false, message: "Published feedback report not found." });
  const format = String(req.query.format || "csv").toLowerCase();
  const safe = String(doc.title).replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").toLowerCase() || "feedback-report";
  if (format === "json") {
    res.setHeader("Content-Disposition", `attachment; filename="${safe}.json"`);
    return res.json({ title: doc.title, exportedAt: new Date().toISOString(), questions: doc.questions, responses: doc.responses });
  }
  res.setHeader("Content-Type", "text/csv; charset=utf-8");
  res.setHeader("Content-Disposition", `attachment; filename="${safe}.csv"`);
  return res.send(buildFeedbackCsv(doc));
};

