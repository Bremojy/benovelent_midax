const messageSocket = read('backend/sockets/messageSocket.js');
const chatProfile = read('backend/utils/chatProfile.js');
const dependentModel = read('backend/models/DependentDocument.js');
const dependentRoutes = read('backend/routes/dependentRoutes.js');
const dependentController = read('backend/controllers/dependentController.js');
const notificationController = read('backend/controllers/notificationController.js');
