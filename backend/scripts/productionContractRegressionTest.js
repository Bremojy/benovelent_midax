assert(accountsPages.every((page) => /finance\/book-balance/.test(page) && /bookBalance/.test(page)), 'all three Accounts pages load the live book balance independently');
assert(/BROADCAST_IN_PROGRESS/.test(notificationController) && /targetedUsers/.test(notificationController) && /pushSent/.test(notificationController), 'broadcast contract is idempotent and reports delivery channels separately');
assert(/Promise\.all\(/.test(adminSupport) && !/Promise\.allSettled/.test(adminSupport), 'Support & Broadcast page propagates independent load failures');
assert(!/superadmin\/messages/.test(sw) && !/SuperAdminMessages/.test(sw), 'service worker contains no removed SuperAdmin chat deep link');
assert(!/MessageCircle/.test(superadminDashboard), 'SuperAdmin dashboard contains no chat icon reference');
const sourceFiles = [...walk(`${ROOT}/src`, ['.js', '.jsx']), ...walk(`${ROOT}/backend`, ['.js']).filter((file) => !file.includes(`${ROOT}/backend/scripts/`)), ...walk(`${ROOT}/public`, ['.js'])];
const stale = [];
for (const file of sourceFiles) {
  const text = read(file.replace(`${ROOT}/`, ''));
  const removedChatRoute = '/superadmin' + '/messages';
  const removedChatComponent = 'SuperAdmin' + 'Messages';
  if (text.includes(removedChatRoute) || text.includes(removedChatComponent)) stale.push(file.replace(`${ROOT}/`, ''));
}
assert(stale.length === 0, `removed SuperAdmin chat references remain: ${stale.join(', ')}`);
pass('production contract regression checks verified');
