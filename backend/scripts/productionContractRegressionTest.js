const financeController = read('backend/controllers/financeController.js');
const sw = read('public/sw.js');
const superadminDashboard = read('src/pages/superadmin/SuperAdminDashboard.jsx');
const accountsPages = [read('src/pages/member/Accounts.jsx'), read('src/pages/admin/AdminAccounts.jsx'), read('src/pages/superadmin/SuperAdminAccounts.jsx')];
const adminMessages = read('src/pages/admin/AdminMessages.jsx');
const messageCenter = read('src/components/chat/MessageCenterPage.jsx');
